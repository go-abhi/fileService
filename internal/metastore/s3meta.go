package metastore

import (
	"context"
	"encoding/json"
	"fmt"
	"io"
	"strconv"
	"strings"
	"sync"
	"time"

	"github.com/go-abhi/fileService/internal/core"
	"github.com/go-abhi/fileService/internal/s3"
)

// S3 stores file records as JSON objects in the bucket, so the service needs
// no database and stays stateless. Layout under the key prefix:
//
//	_meta/<namespace>/<newest-first sort key>_<id>.json   file records
//	_pending/<namespace>/<id>                             markers of in-progress uploads
//
// S3 is strongly consistent, so reads always see the latest write. Record
// updates are last-writer-wins; concurrent completions of the same upload
// write identical records.
type S3 struct {
	c           *s3.Client
	prefix      string
	concurrency int
}

// NewS3 returns a store that writes under prefix (e.g. "files/").
func NewS3(c *s3.Client, prefix string) *S3 {
	if prefix != "" && !strings.HasSuffix(prefix, "/") {
		prefix += "/"
	}
	return &S3{c: c, prefix: prefix, concurrency: 16}
}

type record struct {
	Version int        `json:"v"`
	File    *core.File `json:"file"`
}

// sortKey makes listing return the newest files first: UUIDv7 IDs start with
// a 48-bit millisecond timestamp, which is inverted so that S3's ascending
// key order becomes newest-first.
func sortKey(id string) string {
	ts, err := strconv.ParseUint(strings.ReplaceAll(id[:13], "-", ""), 16, 64)
	if err != nil {
		return "ffffffffffff_" + id
	}
	return fmt.Sprintf("%012x_%s", uint64(0xffffffffffff)-ts, id)
}

func (s *S3) recordPrefix(ns string) string { return s.prefix + "_meta/" + ns + "/" }
func (s *S3) recordKey(ns, id string) string {
	return s.recordPrefix(ns) + sortKey(id) + ".json"
}
func (s *S3) pendingPrefix() string           { return s.prefix + "_pending/" }
func (s *S3) pendingKey(ns, id string) string { return s.pendingPrefix() + ns + "/" + id }

func (s *S3) write(ctx context.Context, f *core.File) error {
	body, err := json.Marshal(record{Version: 1, File: f})
	if err != nil {
		return err
	}
	_, err = s.c.PutObject(ctx, s.recordKey(f.Namespace, f.ID), body, s3.ObjectHeaders{ContentType: "application/json"})
	return err
}

// Create implements core.MetadataStore. IDs are random UUIDs generated by the
// service, so creation does not check for an existing record.
func (s *S3) Create(ctx context.Context, f *core.File) error {
	if f.Status != core.StatusPending {
		return s.write(ctx, f) // no pending marker can exist yet
	}
	return s.Put(ctx, f)
}

// Put implements core.MetadataStore.
func (s *S3) Put(ctx context.Context, f *core.File) error {
	if f.Status == core.StatusPending {
		// Marker first, so the janitor can always find pending uploads.
		if _, err := s.c.PutObject(ctx, s.pendingKey(f.Namespace, f.ID), nil, s3.ObjectHeaders{}); err != nil {
			return err
		}
		return s.write(ctx, f)
	}
	if err := s.write(ctx, f); err != nil {
		return err
	}
	return s.c.DeleteObject(ctx, s.pendingKey(f.Namespace, f.ID))
}

// Get implements core.MetadataStore.
func (s *S3) Get(ctx context.Context, ns, id string) (*core.File, error) {
	return s.read(ctx, s.recordKey(ns, id))
}

func (s *S3) read(ctx context.Context, key string) (*core.File, error) {
	out, err := s.c.GetObject(ctx, key, 0, 0)
	if err != nil {
		if s3.IsNotFound(err) {
			return nil, core.Errorf(core.KindNotFound, "file record not found")
		}
		return nil, err
	}
	defer out.Body.Close()
	body, err := io.ReadAll(io.LimitReader(out.Body, 1<<20))
	if err != nil {
		return nil, err
	}
	var r record
	if err := json.Unmarshal(body, &r); err != nil || r.File == nil {
		return nil, fmt.Errorf("metastore: corrupt record %s: %v", key, err)
	}
	return r.File, nil
}

// Delete implements core.MetadataStore.
func (s *S3) Delete(ctx context.Context, ns, id string) error {
	if err := s.c.DeleteObject(ctx, s.recordKey(ns, id)); err != nil {
		return err
	}
	return s.c.DeleteObject(ctx, s.pendingKey(ns, id))
}

// List implements core.MetadataStore.
func (s *S3) List(ctx context.Context, q core.ListQuery) ([]*core.File, string, error) {
	limit := q.Limit
	if limit <= 0 {
		limit = 50
	}
	in := s3.ListObjectsInput{Prefix: s.recordPrefix(q.Namespace), MaxKeys: limit + 1}
	if q.After != "" {
		in.StartAfter = s.recordKey(q.Namespace, q.After)
	}
	var files []*core.File
	for {
		page, err := s.c.ListObjects(ctx, in)
		if err != nil {
			return nil, "", err
		}
		keys := make([]string, len(page.Objects))
		for i, o := range page.Objects {
			keys[i] = o.Key
		}
		got, err := s.readMany(ctx, keys)
		if err != nil {
			return nil, "", err
		}
		for _, f := range got {
			if f == nil || (!q.IncludePending && f.Status != core.StatusAvailable) {
				continue
			}
			files = append(files, f)
			if len(files) > limit {
				return files[:limit], files[limit-1].ID, nil
			}
		}
		if !page.IsTruncated {
			return files, "", nil
		}
		in.ContinuationToken = page.NextContinuationToken
		in.StartAfter = ""
	}
}

// readMany fetches records concurrently, preserving order. Records deleted
// between listing and reading are returned as nil.
func (s *S3) readMany(ctx context.Context, keys []string) ([]*core.File, error) {
	out := make([]*core.File, len(keys))
	errs := make([]error, len(keys))
	sem := make(chan struct{}, s.concurrency)
	var wg sync.WaitGroup
	for i, k := range keys {
		wg.Add(1)
		sem <- struct{}{}
		go func() {
			defer func() { <-sem; wg.Done() }()
			f, err := s.read(ctx, k)
			if err != nil && !core.IsNotFound(err) {
				errs[i] = err
				return
			}
			out[i] = f
		}()
	}
	wg.Wait()
	for _, err := range errs {
		if err != nil {
			return nil, err
		}
	}
	return out, nil
}

// ListExpiredUploads implements core.MetadataStore.
func (s *S3) ListExpiredUploads(ctx context.Context, now time.Time, limit int) ([]*core.File, error) {
	in := s3.ListObjectsInput{Prefix: s.pendingPrefix()}
	var out []*core.File
	for {
		page, err := s.c.ListObjects(ctx, in)
		if err != nil {
			return nil, err
		}
		for _, o := range page.Objects {
			ns, id, ok := strings.Cut(strings.TrimPrefix(o.Key, s.pendingPrefix()), "/")
			if !ok || !core.ValidID(id) {
				continue
			}
			f, err := s.Get(ctx, ns, id)
			if core.IsNotFound(err) {
				// Orphan marker (record already gone): clean it up once it is
				// old enough not to race with a record being created.
				if o.LastModified.Before(now.Add(-time.Hour)) {
					s.c.DeleteObject(ctx, o.Key)
				}
				continue
			}
			if err != nil {
				return nil, err
			}
			if f.Status != core.StatusPending {
				s.c.DeleteObject(ctx, o.Key)
				continue
			}
			if f.Upload != nil && f.Upload.ExpiresAt.Before(now) {
				out = append(out, f)
				if limit > 0 && len(out) >= limit {
					return out, nil
				}
			}
		}
		if !page.IsTruncated {
			return out, nil
		}
		in.ContinuationToken = page.NextContinuationToken
	}
}

// Ping implements readiness checks.
func (s *S3) Ping(ctx context.Context) error { return s.c.HeadBucket(ctx) }
